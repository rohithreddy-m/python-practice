num1=int(input("Give the Num 1:"))
num2=int(input("Give the Num 2:"))
operation=input("Give the Operations(+,-,*,/):")
if operation=="+":
    print(num1+num2)
elif operation=="-":
    print(num1-num2)
elif operation=="*":
    print(num1*num2)
elif operation=="/":
    print(num1/num2)        
else :
  print("Invalid Operation")    